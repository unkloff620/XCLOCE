// Scans public/skin and writes src/shared/skin-files.ts: { "<slot key>": "<file>?v=<hash>" }.
// Runs automatically before `npm run dev` / `npm run build`; run manually with `npm run skin`.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, extname } from "node:path";

const root = "public/skin";
const out = "src/shared/skin-files.ts";
const EXT = [".webp", ".png", ".jpg", ".jpeg", ".svg"];
const found = {};
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (EXT.includes(extname(name).toLowerCase())) {
      const rel = relative(root, p).split("\\").join("/");
      const key = rel.slice(0, -extname(rel).length);
      const prev = found[key];
      // prefer webp > png > jpg > svg when several formats exist
      if (prev && EXT.indexOf(extname(prev.split("?")[0])) <= EXT.indexOf(extname(rel).toLowerCase())) continue;
      const hash = createHash("sha1").update(readFileSync(p)).digest("hex").slice(0, 8);
      found[key] = `${rel}?v=${hash}`;
    }
  }
}
walk(root);
const sorted = Object.fromEntries(Object.keys(found).sort().map((k) => [k, found[k]]));
writeFileSync(out, `// Generated by scripts/skin-manifest.mjs — do not edit. Lists pictures present in public/skin.\nexport const SKIN_FILES: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`);
console.log(`skin: ${Object.keys(sorted).length} file(s) → ${out}`);
