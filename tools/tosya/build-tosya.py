"""
«Тося» from the artist's layers (tools/tosya/source): the maid dress with the arms (body), the tray in the hands
(tray), three pies on it (pie-l/-c/-r), the head with holes for the eyes (head), the eye whites, the pupils and the
closed lids (head canvas, 726×838). The head is scaled by HEAD_K and set on the neck. The rig: 1000 wide (half of the
body canvas), its top TOP px above the body canvas. Output: public/assets/tosya/<layer>.webp (trimmed, half size) and
src/client/art/tosya-data.ts (the boxes in rig units).
"""
import json, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "source")
OUT = os.path.join(ROOT, "public", "assets", "tosya")
HEAD_K = 1.2
NECK_X, CHIN_Y = 1021, 1222   # the neck's middle and where the chin sits (body canvas)
HEAD_MID_X, HEAD_BOTTOM = 365, 828
TOP = 150
S = 0.5

os.makedirs(OUT, exist_ok=True)
boxes = {}
def put(name, im, x, y):
    im = im.convert("RGBA")
    a = im.getchannel("A").point(lambda v: 255 if v > 20 else 0)
    bb = a.getbbox()
    im = im.crop(bb)
    x, y = x + bb[0], y + bb[1]
    w, h = round(im.width * S), round(im.height * S)
    im.resize((w, h), Image.LANCZOS).save(os.path.join(OUT, f"{name}.webp"), "WEBP", quality=88, method=6)
    boxes[name] = {"x": round(x * S, 1), "y": round((y + TOP) * S, 1), "w": w, "h": h}

for n in ["body", "tray", "pie-l", "pie-c", "pie-r"]:
    put(n, Image.open(os.path.join(SRC, n + ".png")), 0, 0)
hx, hy = NECK_X - HEAD_MID_X * HEAD_K, CHIN_Y - HEAD_BOTTOM * HEAD_K
for n in ["head", "whites", "pupils", "lids"]:
    im = Image.open(os.path.join(SRC, n + ".png")).convert("RGBA")
    im = im.resize((round(im.width * HEAD_K), round(im.height * HEAD_K)), Image.LANCZOS)
    put(n, im, round(hx), round(hy))
# his looks (tools/tosya/source/looks/<look>/, made by the image edits of the maid's layers): body on the same canvas,
# the head on the head canvas with PAD around it (hats stick out), the goods in the pies' places
PAD = 200
LOOKS = os.path.join(SRC, "looks")
for look in sorted(os.listdir(LOOKS)) if os.path.isdir(LOOKS) else []:
    d = os.path.join(LOOKS, look)
    put(f"body-{look}", Image.open(os.path.join(d, "body.png")), 0, 0)
    im = Image.open(os.path.join(d, "head.png")).convert("RGBA")
    im = im.resize((round(im.width * HEAD_K), round(im.height * HEAD_K)), Image.LANCZOS)
    put(f"head-{look}", im, round(hx - PAD * HEAD_K), round(hy - PAD * HEAD_K))
    for k in "lcr":
        put(f"item-{look}-{k}", Image.open(os.path.join(d, f"item-{k}.png")), 0, 0)
H = round((2620 + TOP) * S)
ts = "/* Generated by tools/tosya/build-tosya.py — do not edit by hand. Rig units (1000 wide). */\n"
ts += f"export const TOSYA_SIZE = {{ w: 1000, h: {H} }};\n"
ts += "export const TOSYA_PARTS: Record<string, { x: number; y: number; w: number; h: number }> = " + json.dumps(boxes) + ";\n"
open(os.path.join(ROOT, "src", "client", "art", "tosya-data.ts"), "w").write(ts)
print(boxes, H)
