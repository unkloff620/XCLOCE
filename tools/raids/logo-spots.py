"""
Where a taken building carries its clan's emblem — one rule for every picture (public/assets/raids/[<yard>/]b-*.webp):
the emblem sits on the building's LEFT ROOF CORNER, found on the building itself (its opaque silhouette, not the
picture's empty margin): the strip of the leftmost 16% of the building, the emblem's middle 8% in from its left edge and a
little under the top of that strip — so it always stands on the left corner of the roof, whatever the picture's padding,
a chimney or a tank. → src/content/raid-logos.ts (x, y in % of the picture).
"""
import glob, os, json
import numpy as np
from PIL import Image
ROOT = "public/assets/raids"
out = {}
for p in sorted(glob.glob(f"{ROOT}/b-*.webp") + glob.glob(f"{ROOT}/*/b-*.webp")):
    a = np.array(Image.open(p).convert("RGBA"))[:, :, 3] > 128
    H, W = a.shape
    ys, xs = np.nonzero(a)
    x0, x1, top, bot = xs.min(), xs.max(), ys.min(), ys.max()
    bw, bh = x1 - x0, bot - top
    strip = a[:, x0:int(x0 + bw * 0.16) + 1]
    roof = np.nonzero(strip.any(1))[0].min()
    x, y = x0 + bw * 0.08, roof + bh * 0.06
    key = os.path.relpath(p, ROOT)[:-5]
    out[key] = [round(x / W * 100, 1), round(y / H * 100, 1)]
ts = ("// generated by tools/raids/logo-spots.py — where a taken building's clan emblem sits (its middle), % of the picture:\n"
      "// the left roof corner of the building's own silhouette\n"
      "export const RAID_LOGO_AT: Record<string, [number, number]> = " + json.dumps(out, indent=2) + ";\n")
open("src/content/raid-logos.ts", "w").write(ts)
print(json.dumps(out))
