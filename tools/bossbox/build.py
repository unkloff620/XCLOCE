"""
«Дополнительная награда» (the boss's box, the user's art 2026-11-21): tools/bossbox/source/*.png → public/assets/bossbox/*.webp
and src/client/art/boss-box-layout.ts (where each layer sits).

  box.png     — the small box by the boss; the knife in its window is cut out: the progress shows through it
  board.png   — the window's wooden board; barbg.png — the dark strip behind the bar; bar.png — the bar's frame (open inside,
                the progress runs under it); plank.png, pin.png, clamps.png, nut.png,
                plate.png — the pin that holds the stage (all of these share one 2000×1101 stage: kept in place)

    python3 tools/bossbox/build.py
"""
import os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "public", "assets", "bossbox")
os.makedirs(OUT, exist_ok=True)

def bbox(im):
    a = np.asarray(im)[:, :, 3]
    ys, xs = np.where(a > 8)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1

lines = ["// generated by tools/bossbox/build.py — where the layers of the boss's box window sit (% of the 2000×1101 stage)"]
# the small box: cropped, its window (the progress behind the knife) in % of the crop
box = Image.open(os.path.join(HERE, "source", "box.png")).convert("RGBA")
x0, y0, x1, y1 = bbox(box)
crop = box.crop((x0, y0, x1, y1))
w, h = crop.size
crop.resize((320, round(320 * h / w)), Image.LANCZOS).save(os.path.join(OUT, "box.webp"), quality=90, method=6)
WIN = (437, 449, 1044, 637)  # the window inside the box (source pixels)
win = [(WIN[0] - x0) / w * 100, (WIN[1] - y0) / h * 100, (WIN[2] - x0) / w * 100, (WIN[3] - y0) / h * 100]
lines.append(f"export const BOX_ASPECT = {w / h:.4f};")
lines.append(f"/** the box's window: left, top, right, bottom in % */\nexport const BOX_WINDOW = [{', '.join(f'{v:.2f}' for v in win)}] as const;")

SW, SH = 2000, 1101
layers = {}
for name in ["board", "barbg", "bar", "plank", "pin", "clamps", "nut", "plate"]:
    im = Image.open(os.path.join(HERE, "source", f"{name}.png")).convert("RGBA")
    a, b, c, d = bbox(im)
    part = im.crop((a, b, c, d))
    scale = 0.5
    part.resize((max(1, round(part.width * scale)), max(1, round(part.height * scale))), Image.LANCZOS).save(os.path.join(OUT, f"{name}.webp"), quality=90, method=6)
    layers[name] = (a / SW * 100, b / SH * 100, (c - a) / SW * 100, (d - b) / SH * 100)
lines.append("/** each layer: left, top, width, height in % of the stage */")
lines.append("export const BOX_LAYERS = {")
for k, (l, t, ww, hh) in layers.items():
    lines.append(f"  {k}: [{l:.2f}, {t:.2f}, {ww:.2f}, {hh:.2f}],")
lines.append("} as const;")
# the bar's dark inside (where the progress fills) and the pin's centre (it moves along the bar to the stage's damage)
BAR_IN = (212, 471, 1783, 597)  # the dark strip behind the bar's frame (barbg.png): the progress fills it, under the frame
lines.append(f"/** the bar's inside: left, top, right, bottom in % of the stage */\nexport const BAR_INSIDE = [{BAR_IN[0] / SW * 100:.2f}, {BAR_IN[1] / SH * 100:.2f}, {BAR_IN[2] / SW * 100:.2f}, {BAR_IN[3] / SH * 100:.2f}] as const;")
lines.append(f"/** the pin assembly's centre line (x, % of the stage) as drawn */\nexport const PIN_X = {955 / SW * 100:.2f};")
lines.append(f"export const STAGE_ASPECT = {SW / SH:.4f};")
open(os.path.join(ROOT, "src", "client", "art", "boss-box-layout.ts"), "w").write("\n".join(lines) + "\n")
print("ok", {k: [round(x, 1) for x in v] for k, v in layers.items()})
