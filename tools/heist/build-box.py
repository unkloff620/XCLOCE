"""
«Взлом»: the artist's box (the user 2026-11-28), its layers on one 887×750 canvas in tools/heist/source/box/:
body (the open box from the front), lid (closed), lid-mid (opening, its underside seen), lid-open (standing up, its
inside seen — the loot is laid on it), hasp (the latch on the lid's front), lock (the padlock's body), shackle (its
bow), ring (the staple the bow goes through: drawn over the bow).
The wooden parts are recoloured for each kind of box (bronze — as drawn, silver, gold, diamond); the iron ones stay.
→ public/assets/heist/box/<kind>-<part>.webp, the iron parts once (<part>.webp), <kind>-closed.webp (the still picture
for the small cards) and src/client/art/heist-box-data.ts (each part's box in % of the canvas).
"""
import json, os
import numpy as np, cv2
from PIL import Image

S = "tools/heist/source/box"
O = "public/assets/heist/box"
os.makedirs(O, exist_ok=True)
W, H = 887, 750
K = 0.72  # the big chest is ~230 css px wide: ×2 for the screen's density
WOOD = ["body", "lid", "lid-mid", "lid-open"]
IRON = ["hasp", "lock", "shackle", "ring"]
L = {n: np.array(Image.open(f"{S}/{n}.png").convert("RGBA")) for n in WOOD + IRON}

# the kinds: (hue in OpenCV's 0…180 or None to keep, saturation ×, value ×)
TINT = {"bronze": None, "silver": (10, 0.12, 1.0), "gold": (19, 1.0, 1.1), "diamond": (99, 0.72, 1.02)}


def tint(a, t):
    if t is None: return a
    h, sk, vk = t
    hsv = cv2.cvtColor(a[..., :3], cv2.COLOR_RGB2HSV).astype(np.float32)
    w = np.clip((hsv[..., 1] - 40) / 60, 0, 1)  # only the coloured wood (not the black lines, the grey hinges)
    nh = (h + (hsv[..., 0] - 10)) % 180
    ns = np.clip(hsv[..., 1] * sk, 0, 255)
    nv = np.clip(hsv[..., 2] * (1 + (vk - 1) * w), 0, 255)
    out = np.dstack([hsv[..., 0] * (1 - w) + nh * w, hsv[..., 1] * (1 - w) + ns * w, nv]).astype(np.uint8)
    rgb = cv2.cvtColor(out, cv2.COLOR_HSV2RGB)
    if h == 10 and sk < 0.3:  # silver: a cold touch
        rgb = np.clip(rgb.astype(np.float32) * np.array([0.96, 1.0, 1.06]), 0, 255).astype(np.uint8)
    return np.dstack([rgb, a[..., 3]])


data = {}
pct = lambda v, d: round(v / d * 100, 3)


def save(name, a, box=None):
    im = Image.fromarray(a)
    b = box or im.getbbox()
    w, h = max(1, round((b[2] - b[0]) * K)), max(1, round((b[3] - b[1]) * K))
    im.crop(b).resize((w, h), Image.LANCZOS).save(f"{O}/{name}.webp", quality=86, method=6)
    return b


def bbox(a):
    ys, xs = np.nonzero(a[..., 3] > 6)
    return (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)


for n in WOOD + IRON:
    b = bbox(L[n])
    data[n] = {"x": pct(b[0], W), "y": pct(b[1], H), "w": pct(b[2] - b[0], W), "h": pct(b[3] - b[1], H)}
for n in IRON:
    save(n, L[n], bbox(L[n]))
for kind, t in TINT.items():
    for n in WOOD:
        save(f"{kind}-{n}", tint(L[n], t), bbox(L[n]))
    # the still picture (the small cards): closed, locked
    c = Image.new("RGBA", (W, H))
    for n in ["body", "lid"]: c.alpha_composite(Image.fromarray(tint(L[n], t)))
    for n in ["hasp", "shackle", "lock", "ring"]: c.alpha_composite(Image.fromarray(L[n]))
    cb = bbox(np.array(c))
    c = c.crop((0, cb[1], W, cb[3]))
    c.resize((round(W * 0.36), round(c.height * 0.36)), Image.LANCZOS).save(f"{O}/{kind}-closed.webp", quality=86, method=6)
    data.setdefault("closedTop", pct(cb[1], H))

# the inside of the open lid, where the loot lies (the planks inside its frame)
lo = data["lid-open"]
data["loot"] = {"x": round(lo["x"] + lo["w"] * 0.06, 3), "y": round(lo["y"] + lo["h"] * 0.12, 3), "w": round(lo["w"] * 0.88, 3), "h": round(lo["h"] * 0.72, 3)}
open("src/client/art/heist-box-data.ts", "w").write(
    "/* Generated by tools/heist/build-box.py — do not edit by hand. Each part's box in % of the 887×750 canvas. */\n"
    "export const HEIST_BOX = " + json.dumps(data, indent=2) + " as const;\nexport const HEIST_BOX_RATIO = 887 / 750;\n")
print(json.dumps(data))
