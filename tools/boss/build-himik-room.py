"""
Химик's fight room — his lab (the artist's layers, tools/boss/source/himik/room/, all 2000×3600 but the sky): sky (a
seamless tile — it drifts behind the window), city (the houses and the car in the window), room (the lab, the window
cut out; the artist's layer is ~98 % opaque — made solid), stool (his stool on wheels), rack (the test tubes, the bottles
and the burner), still-b / still-a (the distilling glass: the same glass twice, solid and ~65 % — the poison goes between
them), lamp (the hanging fluorescent lamp — it swings to and fro and blinks).
→ public/assets/arena/himik/ in 1024×1843 + src/client/art/arena-himik-data.ts (the boxes and the points),
public/assets/arena/himik.webp (the still picture) and tools/scene/source/room-lab.png (the home room, without his stool —
the player's own chair stands there).
"""
import json, os
import numpy as np
from PIL import Image
from scipy import ndimage

S = "tools/boss/source/himik/room"
O = "public/assets/arena/himik"
os.makedirs(O, exist_ok=True)
W, H = 2000, 3600
K = 1024 / W
L = {n: Image.open(f"{S}/{n}.png").convert("RGBA") for n in ["city", "room", "stool", "rack", "still-a", "still-b", "lamp"]}
# the room's layer is ~251/255 opaque all over: solid, but the window's hole
a = np.array(L["room"])
a[..., 3] = np.where(a[..., 3] >= 200, 255, a[..., 3])
L["room"] = Image.fromarray(a)
data = {}


def full(name, im, q=84):
    im.resize((1024, round(H * K)), Image.LANCZOS).save(f"{O}/{name}.webp", quality=q, method=6)


def part(name, im, q=88, b=None):
    b = b or im.getbbox()
    w, h = round((b[2] - b[0]) * K), round((b[3] - b[1]) * K)
    im.crop(b).resize((w, h), Image.LANCZOS).save(f"{O}/{name}.webp", quality=q, method=6)
    data[name] = {"x": round(b[0] * K, 1), "y": round(b[1] * K, 1), "w": w, "h": h}
    return b


P = lambda x, y: [round(x * K, 1), round(y * K, 1)]
# the sky: the tile, its drawn size (it slides by one tile, endlessly) and the window's hole it fills
Image.open(f"{S}/sky.png").convert("RGB").resize((560, 560), Image.LANCZOS).save(f"{O}/sky.webp", quality=84, method=6)
data["sky"] = {"tile": round(760 * K, 1), "x": round(930 * K, 1), "y": round(620 * K, 1)}
part("city", L["city"])
full("room", L["room"], 86)
part("stool", L["stool"])
part("rack", L["rack"])
# the distilling glass: the solid copy, the poison over it (in the glass's inside as a mask), the see-through copy over that
sb = part("still-b", L["still-b"])
part("still-a", L["still-a"], b=sb)
g = np.array(L["still-b"]).astype(int)
m = (g[..., 3] > 128) & (g[..., :3].mean(2) > 105)
m = ndimage.binary_erosion(m, iterations=2)
lab, k = ndimage.label(m)
sizes = ndimage.sum(m, lab, range(1, k + 1))
m = np.isin(lab, [i + 1 for i in range(k) if sizes[i] >= 60])
m = ndimage.binary_closing(m, iterations=2)
mask = np.zeros((H, W, 3), np.uint8)  # a luminance mask: white inside, black outside (no alpha — lossy alpha smears)
mask[m] = 255
part("still-mask", Image.fromarray(mask), b=sb)
# the vessels' insides (2000-px): the round flask on the burner, the three cone flasks it drips into
data["flask"] = {"x": round(765 * K, 1), "y": round(1416 * K, 1), "w": round(108 * K, 1), "h": round(114 * K, 1), "lvl": round(1462 * K, 1), "low": round(1496 * K, 1)}
data["cones"] = [
    {"x": round(958 * K, 1), "w": round(80 * K, 1), "bottom": round(1617 * K, 1), "full": round(1548 * K, 1)},
    {"x": round(1042 * K, 1), "w": round(103 * K, 1), "bottom": round(1618 * K, 1), "full": round(1534 * K, 1)},
    {"x": round(1152 * K, 1), "w": round(73 * K, 1), "bottom": round(1617 * K, 1), "full": round(1574 * K, 1)},
]
# the poison's way: up the flask's neck, over the bend, down the condenser, into the middle flask; the side pipes
data["flow"] = [
    [P(820, 1440), P(820, 1352), P(826, 1339), P(846, 1342), P(885, 1360), P(1060, 1430), P(1082, 1440), P(1090, 1456), P(1090, 1600)],
    [P(1090, 1456), P(1004, 1456), P(1000, 1468), P(1000, 1600)],
    [P(1090, 1456), P(1180, 1456), P(1186, 1468), P(1186, 1600)],
]
data["flame"] = P(815, 1556)
# the desk lamp on the left desk: its bulb in the shade and where its light falls
data["desk"] = {"bulb": P(412, 1558), "pool": P(470, 1850)}
# the hanging lamp: the tubes blink (its copy with the tubes off), it swings to and fro — towards us it grows and rises,
# round the far wall's vanishing point
lb = part("lamp", L["lamp"])
la = np.array(L["lamp"]).astype(float)
yy, xx = np.mgrid[0:H, 0:W]
zone = (xx > 560) & (xx < 1510) & (yy > 280) & (yy < 412)
lum = la[..., :3].mean(2, keepdims=True)
off = la.copy()
off[..., :3] = np.where(zone[..., None], (lum * 0.42 + la[..., :3] * 0.13) * np.array([1.0, 0.98, 0.95]), la[..., :3])
part("lamp-off", Image.fromarray(off.clip(0, 255).astype(np.uint8)), b=lb)
data["tubes"] = P(1035, 345)
data["vanish"] = P(1100, 1250)
open("src/client/art/arena-himik-data.ts", "w").write("/* Generated by tools/boss/build-himik-room.py — do not edit by hand. */\nexport const HIMIK_ROOM = " + json.dumps(data, indent=2) + " as const;\n")

# the still picture: the sky's tile behind the window, then the layers
sky = Image.open(f"{S}/sky.png").convert("RGBA").resize((760, 760), Image.LANCZOS)
still = Image.new("RGBA", (W, H), (0, 0, 0, 255))
for x in range(930, 1400, 760):
    still.alpha_composite(sky, (x, 620))
for n in ["city", "room"]:
    still.alpha_composite(L[n])
home = still.copy()
for n in ["rack", "still-b", "still-a", "lamp"]:
    home.alpha_composite(L[n])
still.alpha_composite(L["stool"])
for n in ["rack", "still-b", "still-a", "lamp"]:
    still.alpha_composite(L[n])
still.convert("RGB").resize((1024, round(H * K)), Image.LANCZOS).save("public/assets/arena/himik.webp", quality=84, method=6)
# the home room: the scene canvas 1060×1484 — the picture ×1060/2000, HOME_TOP px off the top (the lamp stays in)
HOME_TOP = 60
home.convert("RGB").resize((1060, round(H * 1060 / W)), Image.LANCZOS).crop((0, HOME_TOP, 1060, HOME_TOP + 1484)).save("tools/scene/source/room-lab.png")
print(json.dumps(data))
