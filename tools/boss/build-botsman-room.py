"""
Боцман's room (the dojo): the artist's layers on one 2000×3000 sheet — tools/boss/source/botsman/room/{room,bag}.png
(the room with an empty black back wall, the punching bag on its chain, in place) →
  public/assets/arena/botsman.webp            — the flat picture (room + bag), 1024×1536, like the other arenas;
  public/assets/arena/botsman/{room,bag,code}.webp — the live room (art/arena-bg.tsx BotsmanRoom): the bag swings on its
      chain, a green code rain runs down the black wall (code: a strip twice the wall's height, its two halves the same);
  tools/scene/source/room-dojo.png            — the home room «Додзё Боцмана» (1060×1484, the scene canvas);
  src/client/art/arena-botsman-data.ts        — where they lie in 1024×1536.
"""
import json, random
import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageFilter

D = "tools/boss/source/botsman/room"
K = 1024 / 2000
WALL = (582, 792, 1418, 1608)      # the black back wall on the sheet
room = Image.open(f"{D}/room.png").convert("RGBA")
bag = Image.open(f"{D}/bag.png").convert("RGBA")
a = np.array(bag); a[..., 3][a[..., 3] < 12] = 0; bag = Image.fromarray(a)

flat = room.copy(); flat.alpha_composite(bag)
flat.convert("RGB").resize((1024, 1536), Image.LANCZOS).save("public/assets/arena/botsman.webp", quality=88, method=6)
import os
os.makedirs("public/assets/arena/botsman", exist_ok=True)
room.convert("RGB").resize((1024, 1536), Image.LANCZOS).save("public/assets/arena/botsman/room.webp", quality=88, method=6)
bb = bag.getbbox()
bc = bag.crop(bb)
bw, bh = round(bc.width * K), round(bc.height * K)
bc.resize((bw, bh), Image.LANCZOS).save("public/assets/arena/botsman/bag.webp", quality=88, method=6)
# the chain's top: its middle on the first rows
al = np.array(bc)[..., 3]
row = next(y for y in range(al.shape[0]) if (al[y] > 60).any())
xs = np.nonzero(al[row + 6] > 60)[0]
pin = [round((bb[0] + xs.mean()) * K, 1), round((bb[1] + row) * K, 1)]

# the code rain for the wall: tileable top to bottom, two tiles stacked (scrolled by one tile height)
wx, wy, ww, wh = [round(v * K) for v in (WALL[0], WALL[1], WALL[2] - WALL[0], WALL[3] - WALL[1])]
S = 2                                   # drawn at twice the size for a sharp picture
TW, TH = ww * S, wh * S
random.seed(11)
tile = Image.new("RGBA", (TW, TH), (0, 0, 0, 0))
d = ImageDraw.Draw(tile)
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 15 * S // 2 + 4)
glyphs = "0123456789ABCDEFZ$#@<>*+=:ЖЗИЛПФЦШЯБДЮ¥£ΣΞΛΨ"
CW, LH = 17, 19
for cx in range(4, TW - 8, CW):
    for _ in range(random.choice([1, 1, 2])):
        n = random.randint(10, 30); y0 = random.randint(0, TH)
        for k in range(n):
            y = (y0 - k * LH) % TH
            t = k / n
            col = (215, 255, 225, 240) if k == 0 else (40, 140 + int(115 * (1 - t) ** 1.4) // 2, 70, int(25 + 200 * (1 - t) ** 1.2))
            d.text((cx, y), random.choice(glyphs), font=font, fill=col)
            if y > TH - LH:                      # wrap: the glyph cut by the bottom edge shows again at the top
                d.text((cx, y - TH), random.choice(glyphs), font=font, fill=col)
tile = Image.alpha_composite(tile.filter(ImageFilter.GaussianBlur(2.4)), tile)
strip = Image.new("RGBA", (TW, TH * 2), (0, 0, 0, 0)); strip.paste(tile, (0, 0)); strip.paste(tile, (0, TH))
strip.save("public/assets/arena/botsman/code.webp", quality=86, method=6)

data = {"bag": {"x": round(bb[0] * K, 1), "y": round(bb[1] * K, 1), "w": bw, "h": bh}, "pin": pin,
        "wall": {"x": wx, "y": wy, "w": ww, "h": wh}}
open("src/client/art/arena-botsman-data.ts", "w").write(
    "/* Generated by tools/boss/build-botsman-room.py — do not edit by hand. Боцман's room in 1024×1536. */\n"
    "export const BOTSMAN_ROOM = " + json.dumps(data) + " as const;\n")

# the home room: the scene canvas 1060×1484, the flat picture scaled to its width and cut at the bottom
s = flat.convert("RGB").resize((1060, round(3000 * 1060 / 2000)), Image.LANCZOS)
s.crop((0, 0, 1060, 1484)).save("tools/scene/source/room-dojo.png")
print(data)
