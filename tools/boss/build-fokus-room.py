"""
Фокус's room, 1060×1484 (the scene canvas; the artist's layers in place, tools/boss/source/fokus/room/): room.png (the
coder's room with the round window), propeller.png (the fan in the window), plant.png (the ivy top right), tree.png
(the tree on the hill behind the window), cat.png, props.png (cans and chip bags on the floor).
→ public/assets/arena/fokus/: room.webp — the room, its round window see-through (the artist's own hole, used as it is: the fan is the
window's grille), the sky, the sun / the moon, the stars and the tree are drawn
behind it (art/arena-fokus.tsx FokusRoom); propeller, plant,
tree, cat; prop-<n>.webp — every thing of props.png on its own (each casts its own shadow); src/client/art/
arena-fokus-data.ts — the boxes; public/assets/arena/fokus.webp and tools/scene/source/room-coder.png — the flat picture
(the places that show the room still, and the home room «Берлога кодера»).
"""
import json, os
import numpy as np
import cv2
from PIL import Image

S = "tools/boss/source/fokus/room"
O = "public/assets/arena/fokus"
os.makedirs(O, exist_ok=True)
W, H = 1060, 1484
# the window: the artist's round hole in room.png (the room is used as it is — the hole is his), its middle and radius
# measured from the hole for the sky behind it (scene units)
_a = np.array(Image.open(f"{S}/room.png"))[..., 3] < 128
_n, _lab, _st, _c = cv2.connectedComponentsWithStats(_a.astype(np.uint8))
_i = 1 + int(np.argmax(_st[1:, 4]))
_x, _y, _w, _h = _st[_i][:4]
WIN = (round(_x + _w / 2, 1), round(_y + _h / 2, 1))
GLASS_R = int(max(_w, _h) / 2)
HUB = (530, 422)


def load(n):
    im = Image.open(f"{S}/{n}.png").convert("RGBA")
    assert im.size == (W, H), (n, im.size)
    return im


room = load("room")
room.save(f"{O}/room.webp", quality=86, method=6)

boxes = {}


def put(name, im, q=88):
    bb = im.getbbox()
    im.crop(bb).save(f"{O}/{name}.webp", quality=q, method=6)
    boxes[name] = {"x": bb[0], "y": bb[1], "w": bb[2] - bb[0], "h": bb[3] - bb[1]}


for n in ["propeller", "plant", "tree", "cat"]:
    put(n, load(n))
# the cat (the artist's cat/body.png + cat/paw.png, 554×269, in place to each other; dimmed already): the tail and the
# raised hind leg cut out of the body to move on their own — the body's box in the room is cat.png's
cb = Image.open(f"{S}/cat/body.png").convert("RGBA")
cpaw = Image.open(f"{S}/cat/paw.png").convert("RGBA")
ca = np.array(cb)
yy, xx = np.mgrid[0:ca.shape[0], 0:ca.shape[1]]
tail = (xx >= 372) & (yy >= 172)
leg = (xx >= 385) & (xx <= 448) & (yy <= 150) & ~tail
parts = {"cat-tail": tail, "cat-leg": leg}
rest = ca.copy()
for nm, m in parts.items():
    im = ca.copy(); im[..., 3] = np.where(m, im[..., 3], 0)
    Image.fromarray(im).save(f"{O}/{nm}.webp", quality=88, method=6, exact=True)
    rest[..., 3] = np.where(m, 0, rest[..., 3])
Image.fromarray(rest).save(f"{O}/cat-body.webp", quality=88, method=6, exact=True)
cpaw.save(f"{O}/cat-paw.webp", quality=88, method=6, exact=True)
bb = cb.getbbox()
cat_box = Image.open(f"{S}/cat.png").getbbox()
sx, sy = (cat_box[2] - cat_box[0]) / (bb[2] - bb[0]), (cat_box[3] - cat_box[1]) / (bb[3] - bb[1])
boxes["cat-rig"] = {"x": round(cat_box[0] - bb[0] * sx, 2), "y": round(cat_box[1] - bb[1] * sy, 2), "w": round(cb.width * sx, 2), "h": round(cb.height * sy, 2), "sx": round(sx, 5), "sy": round(sy, 5)}
# the props: each connected thing on its own (small specks go with their nearest thing)
p = load("props")
a = np.array(p)[..., 3] > 6
a = cv2.morphologyEx(a.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
n, lab, st, _ = cv2.connectedComponentsWithStats(a)
props = []
for i in range(1, n):
    x, y, w, h, area = st[i]
    if area < 400:
        continue
    keep = (lab == i)
    keep = cv2.dilate(keep.astype(np.uint8), np.ones((9, 9), np.uint8)) > 0
    pa = np.array(p).copy()
    pa[..., 3] = np.where(keep, pa[..., 3], 0)
    props.append((y + h, Image.fromarray(pa)))
props.sort(key=lambda t: t[0])
for k, (_, im) in enumerate(props):
    put(f"prop-{k}", im)
print("props", len(props))

# the skies for the window (the yard's day and night skies), cropped to a strip a little taller than the window
for src, dst in (("public/assets/yard/sky.webp", "sky-day"), ("public/assets/yard/sky-dark.webp", "sky-night")):
    sky = Image.open(src).convert("RGB")
    hh = 640
    sky = sky.resize((round(sky.width * hh / sky.height), hh), Image.LANCZOS)
    sky.save(f"{O}/{dst}.webp", quality=80, method=6)
    boxes[dst] = {"w": sky.width, "h": sky.height}

geo = {"win": list(WIN), "glassR": GLASS_R, "hub": list(HUB), **boxes}
ts = "/* Generated by tools/boss/build-fokus-room.py — do not edit by hand. */\n"
ts += "export const FOKUS_ROOM = " + json.dumps(geo, indent=1) + " as const;\n"
open("src/client/art/arena-fokus-data.ts", "w").write(ts)

# the flat picture: the day sky in the window, the tree, the room and its things on top
flat = Image.new("RGBA", (W, H), (0, 0, 0, 255))
sky = Image.open(f"{O}/sky-day.webp").convert("RGBA")
flat.alpha_composite(sky.crop((0, 0, min(sky.width, W), sky.height)), (0, int(WIN[1] - sky.height / 2)))
for n in ["tree", "room", "propeller", "plant", "props"]:
    flat.alpha_composite(room if n == "room" else load(n))
cr = boxes["cat-rig"]
cat_full = cb.copy(); cat_full.alpha_composite(cpaw)
flat.alpha_composite(cat_full.resize((round(cr["w"]), round(cr["h"])), Image.LANCZOS), (round(cr["x"]), round(cr["y"])))
flat.convert("RGB").save("public/assets/arena/fokus.webp", quality=84, method=6)
flat.convert("RGB").save("tools/scene/source/room-coder.png")
print("ok", json.dumps(boxes))
