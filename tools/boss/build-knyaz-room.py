"""
Князь's room (the arena, animated): the artist's layers on one 1024×1536 canvas in tools/boss/source/knyaz/room/ —
room (the window cut out), leaves (behind the window), glass (the wired window pane), inside (the gold vault behind the
door), rim (the door's frame), door (the round vault door). Each layer is trimmed → public/assets/arena/knyaz/<n>.webp
with its box → src/client/art/arena-knyaz-data.ts; the flat picture (all layers, door shut) → public/assets/arena/knyaz.webp
(the home room, the cards, phones without the animated arena).
"""
import json, os
from PIL import Image

D = "tools/boss/source/knyaz/room"
OUT = "public/assets/arena/knyaz"
os.makedirs(OUT, exist_ok=True)
ORDER = ["leaves", "room", "glass", "inside", "rim", "door"]
boxes = {}
flat = Image.new("RGBA", (1024, 1536), (0, 0, 0, 255))
for n in ORDER:
    im = Image.open(f"{D}/{n}.png").convert("RGBA")
    a = im.getchannel("A").point(lambda v: 0 if v < 8 else v)
    im.putalpha(a)
    flat.alpha_composite(im)
    bb = (0, 0, 1024, 1536) if n == "room" else im.getbbox()
    x0, y0, x1, y1 = max(0, bb[0] - 2), max(0, bb[1] - 2), min(1024, bb[2] + 2), min(1536, bb[3] + 2)
    im.crop((x0, y0, x1, y1)).save(f"{OUT}/{n}.webp", "WEBP", quality=86, method=6)
    boxes[n] = {"x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0}
    print(n, boxes[n])
flat.convert("RGB").save("public/assets/arena/knyaz.webp", "WEBP", quality=86, method=6)
ts = "/* Generated by tools/boss/build-knyaz-room.py — do not edit by hand. Layers of Князь's room on its 1024×1536 canvas. */\n"
ts += "export const KNYAZ_ROOM: Record<string, { x: number; y: number; w: number; h: number }> = " + json.dumps(boxes) + ";\n"
open("src/client/art/arena-knyaz-data.ts", "w").write(ts)
