"""
Солнце's fight room (the artist's, tools/boss/source/solntse/room/: room.png 2000×3000 with the round window cut out,
ball.png — the fireball behind it, on the same canvas) → public/assets/arena/solntse/ in 1024×1536:
  room.webp — the room (the window see-through), ball.webp — the fireball cut to itself (its box in arena-sun-data.ts),
  cracks.webp — the room's lava cracks alone, as a glow (bright saturated orange, softened), for the room to boil with;
  public/assets/arena/solntse.webp — the still picture; tools/scene/source/room-forge.png — the home room «Лавовая кузня».
And his card (boss-card-frame-solntse.webp, the cracks dim — card-cool.png) with its lit copy (card-hot.png):
  public/assets/ui/boss-card-frame-solntse.webp + solntse-card-hot.webp + solntse-card-cracks.webp (the cracks alone).
"""
import json
import numpy as np, cv2
from PIL import Image

S = "tools/boss/source/solntse/room"
O = "public/assets/arena/solntse"
import os
os.makedirs(O, exist_ok=True)
K = 1024 / 2000


def glow_of(a, sigma_core=1.4, sigma_halo=10, gain=2.2):
    """the lava cracks of a picture: bright, very saturated orange-yellow — softened into a glow (RGBA)"""
    r, g, b, al = [a[..., i].astype(np.int32) for i in range(4)]
    hot = (r > 220) & (g > 90) & (r - b > 140) & (g - b > 40) & (al > 100)
    m = hot.astype(np.float32)
    core = cv2.GaussianBlur(m, (0, 0), sigma_core)
    halo = cv2.GaussianBlur(m, (0, 0), sigma_halo)
    k = np.clip(core * 1.3 + halo * gain, 0, 1)
    out = np.zeros(a.shape, np.uint8)
    out[..., 0] = 255
    out[..., 1] = np.clip(100 + 150 * np.clip(core * 1.5, 0, 1), 0, 255).astype(np.uint8)
    out[..., 2] = np.clip(20 + 90 * np.clip(core * 1.5, 0, 1), 0, 255).astype(np.uint8)
    out[..., 3] = (k * 255).astype(np.uint8)
    return out


room = Image.open(f"{S}/room.png").convert("RGBA")
ball = Image.open(f"{S}/ball.png").convert("RGBA")
small = room.resize((1024, 1536), Image.LANCZOS)
small.save(f"{O}/room.webp", quality=86, method=6)
ra = np.array(room)
# not the sun gate's spikes and rim (lit metal, not lava): an ellipse round the window, down to the grate under it
yy, xx = np.mgrid[0:3000, 0:2000]
gate = (((xx - 1000) / 800.0) ** 2 + ((yy - 640) / 480.0) ** 2 < 1) & (yy < 880)
ra2 = ra.copy()
ra2[gate, 3] = 0
Image.fromarray(glow_of(ra2)).resize((1024, 1536), Image.LANCZOS).save(f"{O}/cracks.webp", quality=82, method=6)
bb = ball.getbbox()
ball.crop(bb).resize((round((bb[2] - bb[0]) * K), round((bb[3] - bb[1]) * K)), Image.LANCZOS).save(f"{O}/ball.webp", quality=88, method=6)
box = {"x": round(bb[0] * K, 1), "y": round(bb[1] * K, 1), "w": round((bb[2] - bb[0]) * K), "h": round((bb[3] - bb[1]) * K)}
# the window's middle and radius (the see-through hole)
hole = np.array(room)[..., 3] < 128
hole[2000:] = False
ys, xs = np.nonzero(hole)
win = {"cx": round(float(xs.mean()) * K, 1), "cy": round(float(ys.mean()) * K, 1), "r": round(float(xs.max() - xs.min()) / 2 * K, 1)}
# the lamp on the right and its beam (down to the left), in 1024 units
beam = {"lamp": [940, 134], "a": [640, 300], "b": [735, 410]}
open("src/client/art/arena-sun-data.ts", "w").write(
    "/* Generated by tools/boss/build-sun-room.py — do not edit by hand. */\n"
    f"export const SUN_ROOM = {json.dumps({'ball': box, 'win': win, 'beam': beam})} as const;\n")
# the still picture: the ball behind the room
flat = Image.new("RGBA", room.size, (20, 6, 2, 255))
flat.alpha_composite(ball)
flat.alpha_composite(room)
flat.convert("RGB").resize((1024, 1536), Image.LANCZOS).save("public/assets/arena/solntse.webp", quality=86, method=6)
# the home room: the scene canvas 1060×1484 (the 1024×1536 picture ×1060/1024, 53 px off the top)
sc = flat.convert("RGB").resize((1060, round(3000 * 1060 / 2000)), Image.LANCZOS).crop((0, 53, 1060, 53 + 1484))
sc.save("tools/scene/source/room-forge.png")

# the card
cool = Image.open(f"{S}/card-cool.png").convert("RGBA")
hot = Image.open(f"{S}/card-hot.png").convert("RGBA")
cool.save("public/assets/ui/boss-card-frame-solntse.webp", quality=88, method=6)
hot.save("public/assets/ui/solntse-card-hot.webp", quality=88, method=6)
Image.fromarray(glow_of(np.array(hot), 1.0, 6, 1.6)).save("public/assets/ui/solntse-card-cracks.webp", quality=84, method=6)
print("ball", box, "win", win)
