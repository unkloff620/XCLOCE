"""
Нитка's fight room (the artist's layers, tools/boss/source/nitka/room/, all 2000×3000): sky (the evening behind), city
(the houses in the window), trees (in front of the houses — they sway), glass-a / glass-b (the window's glass), room (the
workshop, the window cut out), machine (the sewing machine on the table — it sews now and then), lamp (the hanging
lamp — it swings and flickers; raised by the artist's «14 × Shift + ↑» = 140 px, he could not lift it in his 2000×3000
file without cutting it). → public/assets/arena/nitka/ in 1024×1536 + src/client/art/arena-nitka-data.ts (the boxes),
public/assets/arena/nitka.webp (the still picture) and tools/scene/source/room-workshop.png (the home room).
"""
import json, os
import numpy as np
from PIL import Image

S = "tools/boss/source/nitka/room"
O = "public/assets/arena/nitka"
os.makedirs(O, exist_ok=True)
K = 1024 / 2000
LAMP_UP = 140
L = {n: Image.open(f"{S}/{n}.png").convert("RGBA") for n in ["sky", "city", "trees", "glass-a", "glass-b", "room", "machine", "lamp"]}
lamp = Image.new("RGBA", (2000, 3000), (0, 0, 0, 0))
lamp.alpha_composite(L["lamp"].crop((0, LAMP_UP, 2000, 3000)), (0, 0))
L["lamp"] = lamp
far = L["sky"].copy(); far.alpha_composite(L["city"])
glass = L["glass-a"].copy(); glass.alpha_composite(L["glass-b"])
data = {}


def full(name, im, q=84):
    im.resize((1024, 1536), Image.LANCZOS).save(f"{O}/{name}.webp", quality=q, method=6)


def part(name, im, q=88):
    b = im.getbbox()
    w, h = round((b[2] - b[0]) * K), round((b[3] - b[1]) * K)
    im.crop(b).resize((w, h), Image.LANCZOS).save(f"{O}/{name}.webp", quality=q, method=6)
    data[name] = {"x": round(b[0] * K, 1), "y": round(b[1] * K, 1), "w": w, "h": h}


full("far", far)
part("trees", L["trees"])
part("glass", glass)
full("room", L["room"], 86)
part("machine", L["machine"])
part("lamp", L["lamp"])
# the hanging lamp swings round the top of its cord (above the picture), its bulb; the desk lamp by the sewing machine
data["lampPivot"] = [round(1031 * K, 1), round(-LAMP_UP * K, 1)]
data["bulb"] = [round(1031 * K, 1), round((416 - LAMP_UP) * K, 1)]
data["desk"] = [round(1025 * K, 1), round(857 * K, 1)]
data["window"] = {"x": round(1607 * K, 1), "y": round(116 * K, 1), "w": round(376 * K), "h": round(714 * K)}
open("src/client/art/arena-nitka-data.ts", "w").write("/* Generated by tools/boss/build-nitka-room.py — do not edit by hand. */\nexport const NITKA_ROOM = " + json.dumps(data, indent=2) + " as const;\n")
still = far.copy()
for n in ["trees"]:
    still.alpha_composite(L[n])
still.alpha_composite(glass)
for n in ["room", "machine", "lamp"]:
    still.alpha_composite(L[n])
still.convert("RGB").resize((1024, 1536), Image.LANCZOS).save("public/assets/arena/nitka.webp", quality=84, method=6)
os.makedirs("tools/scene/source", exist_ok=True)
# the home room: the scene canvas 1060×1484 (the picture ×1060/2000, 53 px off the top — as Солнце's)
still.convert("RGB").resize((1060, round(3000 * 1060 / 2000)), Image.LANCZOS).crop((0, 53, 1060, 53 + 1484)).save("tools/scene/source/room-workshop.png")
print(json.dumps(data))
