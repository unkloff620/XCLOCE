// Lists every picture under public/assets and public/bosses → src/client/asset-manifest.ts (used by the loading screen
// to download all art before the game shows). Runs before every build (npm "prebuild"); commit the result too.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const PUB = join(ROOT, "public");
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d).sort()) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(webp|png|jpe?g|svg)$/i.test(f)) files.push("/" + relative(PUB, p).split("\\").join("/"));
  }
};
for (const d of ["assets", "bosses"]) walk(join(PUB, d));
const ts = `/* Generated by tools/asset-manifest.mjs — do not edit by hand. */\nexport const ASSET_FILES: string[] = ${JSON.stringify(files, null, 1)};\n`;
writeFileSync(join(ROOT, "src", "client", "asset-manifest.ts"), ts);
console.log("asset manifest:", files.length, "files");
