"""
The things held in the mouth (slot «Рот»), straightened for the chewing animation (rig.tsx Mouth, screens.css rig-chew):
tools/rig/source/mouth/<id>.png (the artist's picture, at an angle) → turned level, the end that goes into the mouth
(the cigarette's filter) on the left → public/assets/hero/mouth-<id>.webp + src/client/art/mouth-held-data.ts
(the length and thickness in rig units: the rig turns the picture around its left end).
"""
import os, json
import numpy as np, cv2
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "source", "mouth")
OUT = os.path.join(ROOT, "public", "assets", "hero")
# id: (length in rig units, the end in the mouth is on the right of the source picture)
HELD = {"cigarette": (50, True), "toothpick": (52, False), "cigar": (48, True)}
PX = 4  # output pixels per rig unit
data = {}
for n, (length, flip) in HELD.items():
    im = np.array(Image.open(os.path.join(SRC, n + ".png")).convert("RGBA"))
    pad = 40
    im = cv2.copyMakeBorder(im, pad, pad, pad, pad, cv2.BORDER_CONSTANT, value=(0, 0, 0, 0))
    ys, xs = np.nonzero(im[:, :, 3] > 100)
    pts = np.stack([xs, ys], 1).astype(float); c = pts.mean(0)
    d = np.linalg.svd(pts - c)[2][0]
    if d[0] < 0: d = -d
    ang = np.degrees(np.arctan2(d[1], d[0]))
    M = cv2.getRotationMatrix2D((float(c[0]), float(c[1])), float(ang), 1.0)
    big = cv2.warpAffine(im, M, (im.shape[1], im.shape[0]), flags=cv2.INTER_CUBIC, borderValue=(0, 0, 0, 0))
    if flip: big = big[:, ::-1]
    a = big[:, :, 3]
    ys, xs = np.nonzero(a > 20)
    big = big[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    h, w = big.shape[:2]
    k = length * PX / w
    out = Image.fromarray(np.ascontiguousarray(big)).resize((round(w * k), max(1, round(h * k))), Image.LANCZOS)
    out.save(os.path.join(OUT, f"mouth-{n}.webp"), "WEBP", quality=92, method=6)
    data[n] = {"len": length, "thick": round(h * k / PX, 2)}
    print(n, "turned", round(ang, 1), out.size, data[n])
ts = "/* Generated by tools/rig/build-held-mouth.py — do not edit by hand. Rig units. */\n"
ts += "/** things held in the mouth: public/assets/hero/mouth-<id>.webp, level, the end in the mouth on the left */\n"
ts += "export const MOUTH_HELD: Record<string, { len: number; thick: number }> = " + json.dumps(data) + ";\n"
open(os.path.join(ROOT, "src", "client", "art", "mouth-held-data.ts"), "w").write(ts)
