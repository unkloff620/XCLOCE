"""
«Бабочка» — the flipping choreography (screens.css block «Бабочка», rig.tsx ButterflyHand), after the artist's video:
the knife hangs from under the hand (handle A held, its latch end in the hand) and keeps flipping round it.
One cycle, 24 frames a second (46 frames ≈ 1.9 s):
  0–9    the fist holds the closed knife hanging down
  10–20  the hand opens: the blade swings out to the right and down, handle B goes round right → down → left → up
  21–31  the fist holds the open knife, the blade down and a little right
  32–39  the hand opens: the blade swings down → left, handle B round again (right → down → left)
  40–45  the knife flies up over the hand to the left (aerial) and comes down closed into the fist
Channels (deg, clockwise on screen): w — the whole knife on the grip; b — the blade on handle A's pin (0 out down,
180 shut); p — handle B on the blade's pin, absolute (0 along handle A; the CSS gets p − b, it rides on the blade).
The values between the keys are a Catmull-Rom curve sampled every frame, played linearly; the hand swaps by steps.
A ghost of the knife one frame behind (bf-ghost) reads as motion blur on the fast swings.
Run: python3 tools/rig/butterfly-moves.py  (rewrites the block in src/app/screens.css)
"""
import os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
CSS = os.path.join(ROOT, "src", "app", "screens.css")
FPS = 24
N = 46
# frame, w, b, p, hand (F fist, O open)
KEYS = [
    (0, 0, 180, 360, "F"), (5, 3, 180, 362, "F"), (9, 0, 180, 360, "F"),
    (10, -4, 192, 378, "O"), (11, -6, 228, 420, "O"), (12, -4, 270, 465, "O"), (13, 0, 308, 505, "O"),
    (14, 3, 334, 540, "O"), (15, 4, 345, 572, "O"), (16, 3, 350, 610, "O"), (17, 1, 350, 645, "O"),
    (18, -2, 348, 680, "O"), (19, -3, 346, 704, "O"), (20, -2, 345, 716, "O"),
    (21, 0, 345, 720, "F"), (26, 3, 350, 722, "F"), (31, 0, 345, 720, "F"),
    (32, -3, 348, 728, "O"), (33, -5, 368, 765, "O"), (34, -6, 398, 808, "O"), (35, -6, 426, 852, "O"),
    (36, -5, 444, 895, "O"), (37, -4, 450, 932, "O"), (38, -4, 452, 966, "O"), (39, 4, 456, 1000, "O"),
    (40, 45, 474, 1038, "O"), (41, 100, 504, 1070, "O"), (42, 120, 530, 1080, "O"),
    (43, 60, 540, 1080, "F"), (44, 12, 540, 1080, "F"), (45, 0, 540, 1080, "F"),
]


def curve(ch):
    """Catmull-Rom through the keys of one channel, sampled at every frame 0..N-1"""
    xs = [k[0] for k in KEYS]
    ys = [k[ch] for k in KEYS]
    out = []
    for f in range(N):
        i = max(j for j in range(len(xs)) if xs[j] <= f)
        if i == len(xs) - 1:
            out.append(ys[i]); continue
        x0, x1 = xs[i], xs[i + 1]
        y0, y1 = ys[i], ys[i + 1]
        ym = ys[i - 1] if i > 0 else y0
        yp = ys[i + 2] if i + 2 < len(ys) else y1
        xm = xs[i - 1] if i > 0 else x0 - 1
        xp = xs[i + 2] if i + 2 < len(xs) else x1 + 1
        m0 = (y1 - ym) / (x1 - xm) * (x1 - x0)
        m1 = (yp - y0) / (xp - x0) * (x1 - x0)
        t = (f - x0) / (x1 - x0)
        h00, h10, h01, h11 = 2 * t**3 - 3 * t**2 + 1, t**3 - 2 * t**2 + t, -2 * t**3 + 3 * t**2, t**3 - t**2
        out.append(h00 * y0 + h10 * m0 + h01 * y1 + h11 * m1)
    return out


pc = lambda f: f"{f * 100 / N:.3f}".rstrip("0").rstrip(".") + "%"
W, B, P = curve(1), curve(2), curve(3)
hand = []
for f in range(N):
    hand.append(max((k for k in KEYS if k[0] <= f), key=lambda k: k[0])[4])


def rot_frames(name, vals):
    body = " ".join(f"{pc(f)} {{ transform: rotate({v:.1f}deg); }}" for f, v in enumerate(vals))
    body += f" 100% {{ transform: rotate({vals[-1]:.1f}deg); }}"
    return f"@keyframes {name} {{ {body} }}"


def show_frames(name, which):
    keys, prev = [], None
    for f in range(N):
        v = 1 if hand[f] == which else 0
        if v != prev:
            keys.append(f"{pc(f)} {{ opacity: {v}; }}"); prev = v
    keys.append(f"100% {{ opacity: {prev}; }}")
    return f"@keyframes {name} {{ {' '.join(keys)} }}"


dur = f"{N / FPS:.4f}".rstrip("0") + "s"
lag = f"{1 / FPS:.4f}s"
block = f"""/* «Бабочка» in the left hand (rig.tsx ButterflyHand) — generated by tools/rig/butterfly-moves.py, do not edit by hand.
   The knife hangs from under the hand and flips round it ({N} frames at {FPS} fps): bf-w the whole knife on the grip,
   bf-b the blade on handle A's pin, bf-h handle B on the blade's pin; the fist and the open hand swap by steps.
   bf-ghost — the same knife a frame behind, faint: motion blur on the fast swings. Longhands: a shorthand without a
   name is minified to «animation: none». */
.bf-w, .bf-b, .bf-h, .bf-fist, .bf-open {{ animation-duration: {dur}; animation-iteration-count: infinite; animation-timing-function: linear; }}
.bf-fist, .bf-open {{ animation-timing-function: steps(1, end); }}
.bf-ghost {{ opacity: 0.3; }}
.bf-ghost .bf-w, .bf-ghost .bf-b, .bf-ghost .bf-h {{ animation-delay: {lag}; animation-fill-mode: backwards; }}
.bf-w {{ animation-name: bf-w; }}
{rot_frames("bf-w", W)}
.bf-b {{ animation-name: bf-b; }}
{rot_frames("bf-b", B)}
.bf-h {{ animation-name: bf-h; }}
{rot_frames("bf-h", [p - b for p, b in zip(P, B)])}
.bf-fist {{ animation-name: bf-fist; }}
{show_frames("bf-fist", "F")}
.bf-open {{ animation-name: bf-open; opacity: 0; }}
{show_frames("bf-open", "O")}
.rig.still .bf-w, .rig.still .bf-b, .rig.still .bf-h, .rig.still .bf-fist, .rig.still .bf-open {{ animation: none; }} .rig.still .bf-open, .rig.still .bf-ghost {{ opacity: 0; }} .rig.still .bf-fist {{ opacity: 1; }}
@media (prefers-reduced-motion: reduce) {{ .bf-w, .bf-b, .bf-h, .bf-fist, .bf-open {{ animation: none; }} .bf-open, .bf-ghost {{ opacity: 0; }} .bf-fist {{ opacity: 1; }} }}
"""
css = open(CSS).read()
a = css.index("/* «Бабочка» in the left hand")
b = css.index("/* the character editor")
open(CSS, "w").write(css[:a] + block + css[b:])
print(f"{N} frames, {dur}")
