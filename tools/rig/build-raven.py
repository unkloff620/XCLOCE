"""
«Ворон» (the poker's royal flush; the hero's left shoulder): the artist's layers on one 971×591 canvas
(tools/rig/source/raven/): body-r (looking right, the wing apart), body-l (looking left, its wing drawn on it), wing-closed
(the wing lying on body-r), far-half / near-half (the wings a little open: the far one behind the body, the near one in
front), far-full / near-full (the wings spread). Each open wing is bent by puppet deformation into a strip of FRAMES
frames: every pixel turns round the wing's root by an angle growing with its distance from the root (θ = A·t·(r/R)^1.4,
t from -1 to 1 — the tips go down … up, the root stays), so a flap bends the feathers smoothly instead of swinging the
wing stiff. → public/assets/hero/raven/<name>.webp at half size (the strips FRAMES frames wide) + src/client/art/raven-data.ts.
  python3 tools/rig/build-raven.py
"""
import json, os
import numpy as np
from PIL import Image
from scipy import ndimage

S = "tools/rig/source/raven"
O = "public/assets/hero/raven"
os.makedirs(O, exist_ok=True)
W, H = 971, 591
K = 0.5
FRAMES = 13
# the bend (deg at the tip at t = ±1) and which way is up: the far wing goes off to the left, the near one to the right
WINGS = {"far-half": (16, 1), "near-half": (16, -1), "far-full": (24, 1), "near-full": (24, -1)}
data = {"w": W, "h": H, "frames": FRAMES, "roots": {}}


def save(name, im):
    im.resize((round(im.width * K), round(im.height * K)), Image.LANCZOS).save(f"{O}/{name}.webp", quality=88, method=6)


for n in ["body-r", "body-l", "wing-closed"]:
    save(n, Image.open(f"{S}/{n}.png").convert("RGBA"))

# body-air-l: looking left in the air (the wings open) — body-l has its folded wing drawn on, so its head (above the
# neck) goes onto body-r, whose own beak (right of the neck) is left out
r = np.array(Image.open(f"{S}/body-r.png").convert("RGBA")).astype(np.float32)
l = np.array(Image.open(f"{S}/body-l.png").convert("RGBA")).astype(np.float32)
yy, xx = np.mgrid[0:H, 0:W]
r *= ~((xx > 648) & (yy < 190))[..., None]
m = np.clip((170 - yy) / 30, 0, 1)[..., None]
save("body-air-l", Image.fromarray((l * m + r * (1 - m)).astype(np.uint8)))

PAD = 120  # room for the bent tips
for n, (amp, up) in WINGS.items():
    src = np.array(Image.open(f"{S}/{n}.png").convert("RGBA")).astype(np.float32)
    a = src[..., 3] > 100
    ys, xs = np.nonzero(a)
    # the root: the wing's end nearest the body (the far wing's right end, the near wing's left end)
    edge = xs > xs.max() - 45 if up > 0 else xs < xs.min() + 45
    root = (float(xs[edge].mean()), float(ys[edge].mean()))
    R = float(np.hypot(xs - root[0], ys - root[1]).max())
    data["roots"][n] = [round(root[0], 1), round(root[1], 1)]
    big = np.zeros((H + 2 * PAD, W, 4), np.float32)
    big[PAD:PAD + H] = src
    yy, xx = np.mgrid[0:H + 2 * PAD, 0:W].astype(np.float32)
    dx, dy = xx - root[0], yy - (root[1] + PAD)
    r = np.hypot(dx, dy)
    strip = []
    for t in np.linspace(-1, 1, FRAMES):
        th = np.radians(amp * t * up) * np.clip(r / R, 0, 1.3) ** 1.4
        # the output pixel p comes from p turned back by θ(r) (a turn round the root keeps r)
        c, s = np.cos(-th), np.sin(-th)
        sx = root[0] + dx * c - dy * s
        sy = root[1] + PAD + dx * s + dy * c
        out = np.stack([ndimage.map_coordinates(big[..., k], [sy, sx], order=1, cval=0) for k in range(4)], -1)
        strip.append(Image.fromarray(out.clip(0, 255).astype(np.uint8)))
    fw, fh = strip[0].size
    sheet = Image.new("RGBA", (fw * FRAMES, fh))
    for i, f in enumerate(strip):
        sheet.paste(f, (i * fw, 0))
    save(n, sheet)
    print(n, "root", data["roots"][n], "R", round(R))
data["pad"] = PAD
open("src/client/art/raven-data.ts", "w").write("// generated by tools/rig/build-raven.py — «Ворон» on the hero's shoulder: his canvas, the wings' strips and roots\n"
                                                  f"export const RAVEN = {json.dumps(data)} as const;\n")
