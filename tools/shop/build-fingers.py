"""
The shopkeeper's fingers drumming the counter, bent like a puppet (not turned): each finger has a bone from the knuckle
(fixed, on the back of the hand) to the tip; a frame lifts the tip straight up and the finger bends along the bone — no
lift at the knuckle, the full lift at the tip (t^1.5 in between). FRAMES frames per finger, from flat to fully up, in one
sprite strip public/assets/shop/v2/finger-<id>.webp; boxes (percent of the 2000×2800 canvas) → src/client/art/finger-data.ts.
Bones: the artist's marks on the hand (green — the knuckle, yellow — the tip), in canvas pixels.
"""
import json
import numpy as np
import cv2
from PIL import Image

D = "tools/boss/source/shopkeeper/placed"
OUT = "public/assets/shop/v2"
W, H = 2000, 2800
K = 0.6
FRAMES = 8
LIFT = 34            # canvas px the tip goes up at the top frame
# back to front: the index finger is the farthest, the little finger the nearest
BONES = {
    "f1": ((901, 1577), (765, 1664)),   # index
    "f4": ((907, 1602), (783, 1680)),   # middle
    "f2": ((922, 1632), (811, 1689)),   # ring
    "f3": ((929, 1672), (856, 1696)),   # little
}
data = {}
for n, (g, y) in BONES.items():
    a = np.array(Image.open(f"{D}/{n}.png").convert("RGBA")).astype(np.float32)
    ys, xs = np.nonzero(a[:, :, 3] > 10)
    x0, y0, x1, y1 = xs.min() - 6, ys.min() - LIFT - 8, xs.max() + 6, ys.max() + 6
    src = a[y0:y1, x0:x1]
    h, w = src.shape[:2]
    gx, gy = g[0] - x0, g[1] - y0
    bx, by = y[0] - g[0], y[1] - g[1]
    L2 = bx * bx + by * by
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    t = np.clip(((xx - gx) * bx + (yy - gy) * by) / L2, 0, 1.15)
    frames = []
    for k in range(FRAMES):
        lift = LIFT * (k / (FRAMES - 1))
        wgt = t ** 1.5
        # inverse map: an output pixel shows the source pixel that far below it
        my = (yy + lift * wgt).astype(np.float32)
        frames.append(cv2.remap(np.ascontiguousarray(src), xx, my, cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0, 0)))
    strip = np.nan_to_num(np.concatenate(frames, axis=1))
    im = Image.fromarray(np.clip(strip, 0, 255).astype(np.uint8))
    im = im.resize((round(w * K) * FRAMES, round(h * K)), Image.LANCZOS)
    im.save(f"{OUT}/finger-{n}.webp", quality=88, method=6)
    data[n] = {"left": round(x0 / W * 100, 3), "top": round(y0 / H * 100, 3), "width": round(w / W * 100, 3), "height": round(h / H * 100, 3)}
    print(n, im.size, data[n])
ts = "/* generated by tools/shop/build-fingers.py — the shopkeeper's finger strips (FRAMES frames each), boxes in percent of the canvas */\n"
ts += f"export const FINGER_FRAMES = {FRAMES};\nexport const FINGERS: Record<string, {{ left: number; top: number; width: number; height: number }}> = {json.dumps(data, indent=2)};\n"
open("src/client/art/finger-data.ts", "w").write(ts)
