"""«Ящик ништяков» as a case: the layers drawn by the artist on one 652×461 canvas (tools/shop/source/case/*.png)
→ public/assets/shop/v2/case-<layer>.webp (each cut to its own box) + src/client/art/case-data.ts (the boxes in % of
the case's frame: the union of all the layers)."""
import json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "shop", "source", "case")
OUT = os.path.join(ROOT, "public", "assets", "shop", "v2")
LAYERS = ["inner", "base", "lid", "latch-l", "latch-r"]

ims, boxes = {}, {}
for n in LAYERS:
    a = np.array(Image.open(os.path.join(SRC, n + ".png")).convert("RGBA"))
    a[a[:, :, 3] < 40, 3] = 0  # specks of the eraser
    a[a[:, :, 3] == 0, :3] = 0
    ys, xs = np.nonzero(a[:, :, 3])
    boxes[n] = (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    ims[n] = a
x0 = min(b[0] for b in boxes.values()); y0 = min(b[1] for b in boxes.values())
x1 = max(b[2] for b in boxes.values()); y1 = max(b[3] for b in boxes.values())
W, H = x1 - x0, y1 - y0
data = {}
for n in LAYERS:
    bx0, by0, bx1, by1 = boxes[n]
    Image.fromarray(ims[n][by0:by1, bx0:bx1]).save(os.path.join(OUT, f"case-{n}.webp"), quality=90, method=6)
    data[n] = {"left": round((bx0 - x0) / W * 100, 2), "top": round((by0 - y0) / H * 100, 2),
               "width": round((bx1 - bx0) / W * 100, 2), "height": round((by1 - by0) / H * 100, 2)}
ts = "/* Generated by tools/shop/build-case.py — do not edit by hand. Layer boxes in % of the case's frame. */\n"
ts += f"export const CASE_ASPECT = {round(W / H, 4)};\n"
ts += "export const CASE_LAYERS = " + json.dumps(data, indent=2) + " as const;\n"
open(os.path.join(ROOT, "src", "client", "art", "case-data.ts"), "w").write(ts)
print(W, H, data)

# the case seen from the front (the opening window, screens/shop.tsx): closed and open on one 1072×1219 canvas
for n in ("front-closed", "front-open"):
    a = np.array(Image.open(os.path.join(SRC, n + ".png")).convert("RGBA"))
    a[a[:, :, 3] < 40, 3] = 0
    a[a[:, :, 3] == 0, :3] = 0
    im = Image.fromarray(a).resize((644, 732), Image.LANCZOS)  # shown at most ~320 px wide
    im.save(os.path.join(OUT, f"case-{n}.webp"), quality=88, method=6)
print("front views")
