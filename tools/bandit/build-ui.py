"""
«Бандитский фарт»: the artist's layers (tools/bandit/source/ui/<name>.png, each on the 2000×3000 canvas of the screen)
→ cropped to what they hold, at half size: public/assets/bandit/ui/<name>.webp, and their boxes on the canvas
(src/client/art/bandit-ui-data.ts). The 20 cells are one picture (cell.png, the top left one) put at CELL_X × CELL_Y.
"""
import os, json
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "tools", "bandit", "source", "ui")
OUT = os.path.join(ROOT, "public", "assets", "bandit", "ui")
os.makedirs(OUT, exist_ok=True)
CELL_X = [207, 525, 843, 1160, 1478]
CELL_Y = [889, 1195, 1505, 1811]
boxes = {}
for f in sorted(os.listdir(SRC)):
    name = f[:-4]
    im = Image.open(os.path.join(SRC, f)).convert("RGBA")
    bb = im.getbbox()
    im = im.crop(bb)
    im.resize((max(1, round(im.width / 2)), max(1, round(im.height / 2))), Image.LANCZOS).save(os.path.join(OUT, f"{name}.webp"), "WEBP", quality=88, method=6)
    boxes[name] = {"x": bb[0], "y": bb[1], "w": bb[2] - bb[0], "h": bb[3] - bb[1]}
    print(name, boxes[name])
data = {"canvas": [2000, 3000], "cellX": CELL_X, "cellY": CELL_Y, "boxes": boxes}
with open(os.path.join(ROOT, "src", "client", "art", "bandit-ui-data.ts"), "w") as fh:
    fh.write("// generated by tools/bandit/build-ui.py — the artist's slot machine layers on its 2000×3000 canvas\n")
    fh.write(f"export const BANDIT_UI = {json.dumps(data, ensure_ascii=False)} as const;\n")
