"""The exchanger screen (screens/exchange.tsx ExchangeGarage): the artist's layers on one 1080×2400 canvas
(tools/exchange/source/layers/*.png — bg, table, paper, junk, machine, lamp) → public/assets/exchange/<layer>.webp,
each cut to its own box; the boxes (percent of the canvas) → src/client/art/exchange-data.ts.
The dealer behind the table is the yard kiosk's animated layers (public/assets/yard/kiosk), placed at DEALER."""
import os, json
import numpy as np, cv2
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "source", "layers")
OUT = os.path.join(ROOT, "public", "assets", "exchange")
os.makedirs(OUT, exist_ok=True)
CW, CH = 1080, 2400
SCALE = 0.75   # output size of the canvas: 810×1800
boxes = {}
for name in ["bg", "table", "paper", "junk", "machine", "lamp"]:
    im = np.array(Image.open(os.path.join(SRC, name + ".png")).convert("RGBA"))
    if name != "bg":
        a = im[:, :, 3]
        a[a < 24] = 0
        # keep the picture itself: drop specks and stray strokes (components far smaller than the biggest)
        n, lab, st, _ = cv2.connectedComponentsWithStats((a > 0).astype(np.uint8))
        big = st[1:, 4].max()
        for i in range(1, n):
            if st[i][4] < big * 0.02: a[lab == i] = 0
        im[:, :, 3] = a
        im[a == 0, :3] = 0
        ys, xs = np.nonzero(a)
        x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    else:
        x0, y0, x1, y1 = 0, 0, CW, CH
    crop = Image.fromarray(im[y0:y1, x0:x1])
    crop = crop.resize((round((x1 - x0) * SCALE), round((y1 - y0) * SCALE)), Image.LANCZOS)
    if name == "bg": crop = crop.convert("RGB")
    crop.save(os.path.join(OUT, name + ".webp"), quality=80 if name == "bg" else 86, method=6)
    boxes[name] = [round(x0 / CW * 100, 2), round(y0 / CH * 100, 2), round((x1 - x0) / CW * 100, 2), round((y1 - y0) / CH * 100, 2)]
    print(name, boxes[name], os.path.getsize(os.path.join(OUT, name + ".webp")) // 1024, "KB")
ts = "/* Generated by tools/exchange/build.py — do not edit by hand. Boxes: [left, top, width, height] in percent of the 1080×2400 scene. */\n"
ts += "export const XG_BOX: Record<string, [number, number, number, number]> = " + json.dumps(boxes) + ";\n"
open(os.path.join(ROOT, "src", "client", "art", "exchange-data.ts"), "w").write(ts)
