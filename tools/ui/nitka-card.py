"""
Нитка's mentor card (the artist's layers, 1200×520, tools/ui/source/nitka-card/L00…L26 — the order of his PSD):
L26 the card itself (the frame, the denim, the pockets, the stripes) → public/assets/ui/boss-card-frame-nitka.webp;
L25 the needle, L00 its thread, the 24 stitches of «НИТКА» (his own numbering of them in the layer names: the order
they are sewn in) → one sprite public/assets/ui/nitka-card-sew.webp, and their places in
src/client/art/nitka-card-data.ts (the card's pixels): each stitch's box, its two ends (from where to where it is
sewn), the needle's point and eye.
  python3 tools/ui/nitka-card.py
"""
import json
import numpy as np
from PIL import Image

SRC = "tools/ui/source/nitka-card"
# the layer of each stitch, in his order 1…24 (the PSD's names: 1_00LL_<n>)
STITCH = ["L24", "L23", "L03", "L21", "L22", "L17", "L18", "L06", "L05", "L11", "L14", "L02",
          "L19", "L20", "L01", "L15", "L16", "L13", "L12", "L10", "L09", "L04", "L07", "L08"]
L = lambda n: Image.open(f"{SRC}/{n}.png").convert("RGBA")

Image.open(f"{SRC}/L26.png").convert("RGBA").save("public/assets/ui/boss-card-frame-nitka.webp", quality=90, method=6)

def ends(a):
    """the two ends of a stroke (the far points along its main axis, 1.5 px in)"""
    ys, xs = np.nonzero(a[..., 3] > 100)
    p = np.stack([xs, ys], 1).astype(float) + 0.5
    c = p.mean(0)
    _, _, vt = np.linalg.svd(p - c, full_matrices=False)
    d = vt[0]
    t = (p - c) @ d
    return c + d * (t.min() + 1.5), c + d * (t.max() - 1.5)

parts, x = [], 0
crops = []
for name in STITCH + ["L25", "L00"]:
    im = L(name)
    box = im.getbbox()
    box = (box[0] - 1, box[1] - 1, box[2] + 1, box[3] + 1)
    crops.append((im.crop(box), x))
    parts.append({"x": box[0], "y": box[1], "w": box[2] - box[0], "h": box[3] - box[1], "sx": x, "a": np.array(im)})
    x += box[2] - box[0] + 2
H = max(p["h"] for p in parts)
sheet = Image.new("RGBA", (x, H))
for im, sx in crops: sheet.paste(im, (sx, 0))
sheet.save("public/assets/ui/nitka-card-sew.webp", lossless=True, method=6, exact=True)

r1 = lambda v: [round(float(v[0]), 1), round(float(v[1]), 1)]
out = {"sheet": [x, H], "stitches": []}
nxt = np.mean(ends(parts[1]["a"]), 0)
prev = None
for p in parts[:24]:
    a, b = ends(p["a"])
    # sewn from the end nearer the last one's end (the first: from the end away from the second)
    if (prev is None and np.hypot(*(a - nxt)) < np.hypot(*(b - nxt))) or (prev is not None and np.hypot(*(a - prev)) > np.hypot(*(b - prev))): a, b = b, a
    prev = b
    out["stitches"].append({k: p[k] for k in ("x", "y", "w", "h", "sx")} | {"a": r1(a), "b": r1(b)})
nd, th = parts[24], parts[25]
a, b = ends(nd["a"])
tip, eye = (a, b) if a[0] < b[0] else (b, a)
out["needle"] = {k: nd[k] for k in ("x", "y", "w", "h", "sx")} | {"tip": r1(tip), "eye": r1(eye)}
out["thread"] = {k: th[k] for k in ("x", "y", "w", "h", "sx")}
open("src/client/art/nitka-card-data.ts", "w").write(
    "// generated by tools/ui/nitka-card.py — the stitches of «НИТКА» on Нитка's card, the needle and its thread (the card's pixels, 1200×520)\n"
    f"export const NITKA_CARD = {json.dumps(out)} as const;\n")
print(json.dumps(out)[:600])
