"""
Псих's mentor card (the artist's layers, 1200×520, tools/ui/source/psih-card/ — his PSD, top first): knife (the bloody knife
lying in the top right), cut-c / cut-b / cut-a (three slashes across the card), frame (the card: the rusty frame, the
plaid shirt, the torn flaps, the chains, the blood).
→ public/assets/ui/boss-card-frame-psih.webp (the nine-slice frame), psih-card-knife.webp, psih-card-cut-{a,b,c}.webp (each
cropped) and src/client/art/psih-card-data.ts: their boxes, each slash's two ends (in the order it is cut: from the end its
blood runs away from), the knife's point and its handle's end.
  python3 tools/ui/psih-card.py
"""
import json
import numpy as np
from PIL import Image

SRC = "tools/ui/source/psih-card"
O = "public/assets/ui"
L = {n: Image.open(f"{SRC}/{n}.png").convert("RGBA") for n in ["frame", "knife", "cut-a", "cut-b", "cut-c"]}
L["frame"].save(f"{O}/boss-card-frame-psih.webp", quality=90, method=6)
data = {}


def ends(a):
    ys, xs = np.nonzero(a[..., 3] > 140)
    p = np.stack([xs, ys], 1).astype(float)
    c = p.mean(0)
    _, _, vt = np.linalg.svd(p - c, full_matrices=False)
    d = vt[0]
    t = (p - c) @ d
    return c + d * np.percentile(t, 0.3), c + d * np.percentile(t, 99.7)


r1 = lambda v: [round(float(v[0]), 1), round(float(v[1]), 1)]
for n in ["knife", "cut-a", "cut-b", "cut-c"]:
    im = L[n]
    a = np.array(im)
    a[a[..., 3] < 6] = 0
    im = Image.fromarray(a)
    b = im.getbbox()
    b = (max(0, b[0] - 2), max(0, b[1] - 2), min(1200, b[2] + 2), min(520, b[3] + 2))
    im.crop(b).save(f"{O}/psih-card-{n}.webp", quality=90, method=6)
    data[n] = {"x": b[0], "y": b[1], "w": b[2] - b[0], "h": b[3] - b[1]}
    if n != "knife":
        p, q = ends(np.array(im))
        data[n]["a"], data[n]["b"] = r1(p), r1(q)
# the slashes: cut from left to right (a: the left end), in the order a hand would — down from the top left first
for n in ["cut-a", "cut-b", "cut-c"]:
    if data[n]["a"][0] > data[n]["b"][0]:
        data[n]["a"], data[n]["b"] = data[n]["b"], data[n]["a"]
# the knife: its point (the far left low end) and the end of its handle (the ring)
k = np.array(L["knife"])
ys, xs = np.nonzero(k[..., 3] > 140)
s = xs - ys
data["knife"]["tip"] = r1((xs[np.argsort(s)[:12]].mean(), ys[np.argsort(s)[:12]].mean()))
data["knife"]["end"] = r1((xs[np.argsort(s)[-12:]].mean(), ys[np.argsort(s)[-12:]].mean()))
open("src/client/art/psih-card-data.ts", "w").write(
    "// generated by tools/ui/psih-card.py — Псих's card (the card's pixels, 1200×520): the knife and the three slashes it cuts\n"
    f"export const PSIH_CARD = {json.dumps(data)} as const;\n")
print(json.dumps(data))
