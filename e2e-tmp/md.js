const { chromium } = require('playwright');
const B = 'http://localhost:3000';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await ctx.addInitScript((g) => { try { localStorage.setItem('xc2_guest', g); localStorage.setItem('xc2_leaders_open', '0'); } catch {} }, require('crypto').randomUUID());
  const P = await ctx.newPage();
  P.on('pageerror', (e) => console.log('PAGEERR ' + String(e).slice(0, 200)));
  await P.goto(B + '/'); await P.waitForSelector('.nav', { timeout: 60000 }); await P.waitForTimeout(1200);
  const token = await P.evaluate(() => localStorage.getItem('xc2_token'));
  const ver = (await fetch(B + '/api/version')).headers.get('x-app-version') || 'dev';
  const H = (t) => ({ 'content-type': 'application/json', authorization: 'Bearer ' + t, 'x-app-version': ver });
  const A = (type, body = {}) => fetch(B + '/api/action', { method: 'POST', headers: H(token), body: JSON.stringify({ type, ...body }) }).then((r) => r.json());
  await A('help_seen', { topic: 'first-steps' });
  const st = await (await fetch(B + '/api/state', { headers: H(token) })).json(); const pid = (st.state ?? st).player.id;
  const al = await (await fetch(B + '/api/admin/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ dev: 1 }) })).json();
  const ad = (edit) => fetch(B + '/api/admin', { method: 'POST', headers: H(al.token), body: JSON.stringify({ op: 'edit', id: pid, edit }) }).then((r) => r.json());
  console.log('give', JSON.stringify(await ad({ op: 'set_item', item: 'rug-pull-gun', qty: 200 })).slice(0, 120));
  await P.goto(B + '/bosses/datsik'); await P.waitForSelector('.mode-pick', { timeout: 30000 }); await P.waitForTimeout(1200);
  console.log('modes', await P.evaluate(() => [...document.querySelectorAll('.mode-btn')].map((e) => e.innerText.replace(/\n/g, ' ')).join(' / ')));
  console.log('hint', await P.evaluate(() => document.querySelector('.mode-hint')?.innerText));
  console.log('plate medal', await P.evaluate(() => document.querySelector('.door-plate .medal-chip')?.innerText));
  await P.click('.mode-btn.blat'); await P.waitForTimeout(400);
  console.log('hint blat', await P.evaluate(() => document.querySelector('.mode-hint')?.innerText));
  await P.click('.mode-btn.pacan'); await P.waitForTimeout(300);
  await P.click('.door-leaf'); await P.waitForTimeout(3500);
  console.log('in fight', !!(await P.$('.fight-page')), await P.evaluate(() => document.querySelector('.fight-head')?.innerText.replace(/\n/g, ' | ')));
  const r = await A('attack', { weapon: 'rug-pull-gun', count: 10 });
  console.log('attack', JSON.stringify(r.result ?? r.error).slice(0, 160));
  await P.waitForTimeout(4000);
  console.log('result', await P.evaluate(() => document.querySelector('.result-gains')?.innerText.replace(/\n/g, ' | ')));
  console.log('medal in result', !!(await P.$('.result-gains .bcoin')));
  await P.goto(B + '/bosses/datsik'); await P.waitForSelector('.mode-pick', { timeout: 30000 }); await P.waitForTimeout(1500);
  console.log('modes after', await P.evaluate(() => [...document.querySelectorAll('.mode-btn')].map((e) => e.innerText.replace(/\n/g, ' ')).join(' / ')));
  await b.close(); console.log('DONE');
})().catch((e) => { console.log('ERR', String(e).slice(0, 600)); process.exit(0); });
