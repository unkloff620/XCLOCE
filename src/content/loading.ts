const GENERIC = ["Ищем дно графика…", "Согласовываем загрузку с руководством…", "Прогреваем видеокарты…", "HODL… ещё чуть-чуть…"];

/** a joke for the picture with this URL; `seed` picks the variant so the same picture always gets the same line */
export function resourceLine(url: string | null, seed = 0): string {
  const rule = url ? RESOURCE_LINES.find((r) => r.test.test(url)) : undefined;
  const lines = rule?.lines ?? GENERIC;
  return lines[Math.abs(seed) % lines.length];
}

