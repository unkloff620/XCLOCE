/**
 * Talking to the dealer in the garage (a tap on the exchange machine). He asks what you want: a talk or an exchange.
 * A talk — once a Moscow day, only while the exchange is open: five of his lines, three answers each (a good one,
 * a so-so one, a rude one). The better the talk, the bigger the chance he gives a better rate for a while.
 * Which talk you get today depends on the day and the player (the same on the client and the server).
 */
export interface TalkAnswer { text: string; score: 0 | 1 | 2; reply: string }
export interface TalkStep { say: string; answers: [TalkAnswer, TalkAnswer, TalkAnswer] }
export interface DealerTalk { id: string; steps: TalkStep[] }

/** the better rate: this much more of the currency you get, for this long */
export const TALK_BONUS = 0.1;
export const TALK_BONUS_MS = 2 * 3600_000;
/** the chance of the better rate by how good the talk was (the score of the best possible answers — 2 a line) */
export function talkChance(score: number, max: number): number {
  const k = max > 0 ? score / max : 0;
  return k >= 1 ? 0.6 : k >= 0.8 ? 0.35 : k >= 0.65 ? 0.15 : 0;
}
/** a good talk: most answers were the good ones (he says it was a nice talk even without the better rate) */
export const talkWasGood = (score: number, max: number) => score / max >= 0.65;

