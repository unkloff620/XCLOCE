/**
 * Talking to the dealer in the garage (a tap on the exchange machine). He asks what you want: a talk or an exchange.
 * A talk — once a Moscow day, only while the exchange is open: three of his lines, three answers each (a good one,
 * a so-so one, a rude one). The better the talk, the bigger the chance he gives a better rate for a while.
 * Which talk you get today depends on the day and the player (the same on the client and the server).
 */
export interface TalkAnswer { text: string; score: 0 | 1 | 2; reply: string }
export interface TalkStep { say: string; answers: [TalkAnswer, TalkAnswer, TalkAnswer] }
export interface DealerTalk { id: string; steps: [TalkStep, TalkStep, TalkStep] }

