/** today's talk for this player ("YYYY-MM-DD" Moscow day) */
export function talkOfDay(day: string, pid: number): DealerTalk {
  let h = pid * 2654435761;
  for (const ch of day) h = (Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0);
  return DEALER_TALKS[(h >>> 0) % DEALER_TALKS.length];
}

export function talkScore(talk: DealerTalk, answers: number[]): number {
  return talk.steps.reduce((s, st, i) => s + (st.answers[answers[i]]?.score ?? 0), 0);
}
